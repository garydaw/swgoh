async function showAskForAccount(interaction) {

  const modal = new ModalBuilder()
    .setCustomId('account_name_search')
    .setTitle('Find your SWGOH account');

  const nameInput = new TextInputBuilder()
    .setCustomId('player_name')
    .setLabel('Enter the first part of your player name')
    .setPlaceholder('e.g. Bobba')
    .setStyle(TextInputStyle.Short)
    .setRequired(true)
    .setMinLength(2)
    .setMaxLength(20);

  const row = new ActionRowBuilder()
    .addComponents(nameInput);

  modal.addComponents(row);

  await interaction.showModal(modal);
}

async function showPlayerMatches(interaction, result) {
  
  const selectMenu = new StringSelectMenuBuilder()
    .setCustomId(`link_account_select`)
    .setPlaceholder('Select a Player')
    .addOptions(
      ...result.possiblePlayers.map(player => ({
        label: player.ally_name,
        value: String(player.ally_code)
      })),
      {
        label: 'None of the Above',
        value: 'not_in_list'
      }
    );

  const row = new ActionRowBuilder()
    .addComponents(selectMenu);

  await interaction.reply({
    content: 'We found the following possible matches based on your display name/response. Please select your account from the list below:',
    components: [row]
  });
}

async function checkPlayer(interaction, userId, userName, allowModal = true) {
  const result = await apiRequest(
    `/general/player/check/${encodeURIComponent(userId)}/${encodeURIComponent(userName)}`
  );

  if (result.exists) {
    await interaction.reply({
      content: `Your Discord account is already linked to the game profile for ${result.player.ally_name} (${result.player.ally_code}). If this is wrong message Bobba Daw.`,
      flags: MessageFlags.Ephemeral
    });

  } else if (result.possiblePlayers.length > 0) {
    await showPlayerMatches(interaction, result);

  } else if (allowModal) {
    await showAskForAccount(interaction);

  } else {
    await interaction.reply({
      content: `Sorry, I couldn't find any players matching "${userName}". Please try another name.`,
      flags: MessageFlags.Ephemeral
    });
  }
}